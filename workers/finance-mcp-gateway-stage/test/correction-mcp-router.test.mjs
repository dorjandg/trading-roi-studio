const fake=async(url,init)=>{requested++;assert.equal(url,"https://finance-correction-api-isolated.internal/api/finance?resource=transaction-change-preview");assert.equal(init.headers["cf-access-jwt-assertion"],"jwt");assert.deepEqual(JSON.parse(init.body),args);return {ok:true,json:async()=>({previewOnly:true,saved:false,approval_ticket:"opaque",before:"Old",after:"New"})}};
const env={FINANCE_CORRECTION_API:{fetch:fake}};
const call=(name,arguments_)=>({jsonrpc:"2.0",id:1,method:"tools/call",params:{name,arguments:arguments_}});
const list=await routeMcp({jsonrpc:"2.0",id:1,method:"tools/list"},env,null);
assert.deepEqual(list.result.tools.map(t=>t.name),["finance_correction_preview"]);
const disabled=await routeMcp(call("finance_correction_save",{...args,confirmed:true,approval_ticket:"signed-ticket-placeholder"}),env,"jwt");
assert.equal(disabled.error.code,-32602);
const bad=await routeMcp(call("finance_correction_preview",{...args,field:"amount"}),env,"jwt");
assert.equal(bad.error.code,-32602);
const noBinding=await routeMcp(call("finance_correction_preview",args),{},"jwt");
assert.equal(noBinding.error.code,-32002);
const unauth=await routeMcp(call("finance_correction_preview",args),env,null);
assert.equal(unauth.error.code,-32001);
const good=await routeMcp(call("finance_correction_preview",args),env,"jwt");
assert.equal(good.result.isError,undefined);assert.equal(requested,1);
